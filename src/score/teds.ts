// Zhang–Shasha exact tree edit distance
// ---------------------------------------------------------------------------

/** Flattened postorder view of a TableNode tree. */
interface Flat {
  n: number;
  tags: string[]; // 1-based
  colspan: Int32Array;
  rowspan: Int32Array;
  contents: (string | null)[];
  /** cell content split into Unicode code points (matches Python list(text)) */
  codePoints: (string[] | null)[];
  /** l[i] = postorder index of leftmost leaf descendant of node i (1-based) */
  l: Int32Array;
  keyroots: number[];
}

function flatten(root: TableNode): Flat {
  const tags: string[] = [''];
  const contents: (string | null)[] = [null];
  const colspanArr: number[] = [0];
  const rowspanArr: number[] = [0];
  const lArr: number[] = [0];

  const visit = (node: TableNode): number => {
    let leftmost = 0;
    for (let c = 0; c < node.children.length; c++) {
      const childLeftmost = visit(node.children[c]);
      if (c === 0) leftmost = childLeftmost;
    }
    tags.push(node.tag);
    colspanArr.push(node.colspan);
    rowspanArr.push(node.rowspan);
    contents.push(node.content);
    const idx = tags.length - 1;
    lArr.push(node.children.length === 0 ? idx : leftmost);
    return lArr[idx];
  };
  visit(root);

  const n = tags.length - 1;
  const l = Int32Array.from(lArr);
  // keyroots: nodes with no ancestor sharing the same leftmost leaf
  // (i.e. the highest node for each distinct l value)
  const seen = new Set<number>();
  const keyroots: number[] = [];
  for (let idx = n; idx >= 1; idx--) {
    if (!seen.has(l[idx])) {
      seen.add(l[idx]);
      keyroots.push(idx);
    }
  }
  keyroots.sort((a, b) => a - b);
  const codePoints = contents.map((c) => (c === null || c.length === 0 ? null : Array.from(c)));
  return {
    n,
    tags,
    colspan: Int32Array.from(colspanArr),
    rowspan: Int32Array.from(rowspanArr),
    contents,
    codePoints,
    l,
    keyroots,
  };
}

/** Levenshtein distance over Unicode code points (matches Python list(text)). */
function levenshtein(a: string[], b: string[]): number {
  const m = a.length;
  const n = b.length;
  if (m === 0) return n;
  if (n === 0) return m;
  let prev = new Int32Array(n + 1);
  let cur = new Int32Array(n + 1);
  for (let j = 0; j <= n; j++) prev[j] = j;
  for (let i = 1; i <= m; i++) {
    cur[0] = i;
    const ai = a[i - 1];
    for (let j = 1; j <= n; j++) {
      const sub = prev[j - 1] + (ai === b[j - 1] ? 0 : 1);
      const del = prev[j] + 1;
      const ins = cur[j - 1] + 1;
      cur[j] = sub < del ? (sub < ins ? sub : ins) : del < ins ? del : ins;
    }
    [prev, cur] = [cur, prev];
  }
  return prev[n];
}

/** Zhang–Shasha TED between two flattened trees under the PubTabNet cost model. */
function treeEditDistance(t1: Flat, t2: Flat, structureOnly: boolean): number {
  const n1 = t1.n;
  const n2 = t2.n;
  const stride = n2 + 1;
  const td = new Float64Array((n1 + 1) * stride); // permanent tree distances
  const fd = new Float64Array((n1 + 1) * stride); // forest-distance scratch

  // rename-cost memo keyed by node-index pair (NaN = not yet computed)
  const renameCache = new Float64Array((n1 + 1) * stride).fill(NaN);
  const EMPTY: string[] = [];
  const rename = (i: number, j: number): number => {
    if (t1.tags[i] !== t2.tags[j] || t1.colspan[i] !== t2.colspan[j] || t1.rowspan[i] !== t2.rowspan[j]) return 1;
    if (t1.tags[i] === 'td' && !structureOnly) {
      const ca = t1.codePoints[i];
      const cb = t2.codePoints[j];
      if (ca === null && cb === null) return 0; // both cells empty
      const key = i * stride + j;
      let d = renameCache[key];
      if (Number.isNaN(d)) {
        const la = ca === null ? 0 : ca.length;
        const lb = cb === null ? 0 : cb.length;
        d = levenshtein(ca ?? EMPTY, cb ?? EMPTY) / Math.max(la, lb);
        renameCache[key] = d;
      }
      return d;
    }
    return 0;
  };

  const l1 = t1.l;
  const l2 = t2.l;
  for (const kr1 of t1.keyroots) {
    const li = l1[kr1];
    for (const kr2 of t2.keyroots) {
      const lj = l2[kr2];
      // forest distance over subforests rooted at kr1/kr2, offsets from li/lj
      fd[0] = 0;
      for (let x = 1, row = stride; x <= kr1 - li + 1; x++, row += stride) fd[row] = fd[row - stride] + 1;
      for (let y = 1; y <= kr2 - lj + 1; y++) fd[y] = fd[y - 1] + 1;
      for (let i1 = li, x = 1; i1 <= kr1; i1++, x++) {
        const row = x * stride;
        const prow = row - stride;
        for (let j1 = lj, y = 1; j1 <= kr2; j1++, y++) {
          const delCost = fd[prow + y] + 1;
          const insCost = fd[row + y - 1] + 1;
          if (l1[i1] === li && l2[j1] === lj) {
            const ren = fd[prow + y - 1] + rename(i1, j1);
            const best = delCost < insCost ? (delCost < ren ? delCost : ren) : insCost < ren ? insCost : ren;
            fd[row + y] = best;
            td[i1 * stride + j1] = best;
          } else {
            const bridge = fd[(l1[i1] - li) * stride + (l2[j1] - lj)] + td[i1 * stride + j1];
            fd[row + y] =
              delCost < insCost ? (delCost < bridge ? delCost : bridge) : insCost < bridge ? insCost : bridge;
          }
        }
      }
    }
  }
  return td[n1 * stride + n2];
}

/**
 * Tree-Edit-Distance-based Similarity between two table HTML strings. 0..1.
 *
 * @param predHtml predicted table HTML (a bare `<table>...</table>` fragment
 *   or any HTML containing one)
 * @param gtHtml   ground-truth table HTML
 * @param opts.structureOnly ignore cell text; score structure alone (S-TEDS)
 */
export function teds(predHtml: string, gtHtml: string, opts?: { structureOnly?: boolean }): number {
  if (!predHtml || !gtHtml) return 0;
  const pred = parseTableHtml(predHtml);
  const gt = parseTableHtml(gtHtml);
  if (!pred || !gt) return 0;

  const f1 = flatten(pred);
  const f2 = flatten(gt);
  // Reference counts table.xpath('.//*'): descendants only, root excluded.
  const denom = Math.max(f1.n - 1, f2.n - 1);
  const dist = treeEditDistance(f1, f2, opts?.structureOnly ?? false);
  if (denom <= 0) {
    // Both tables are bare <table/> nodes; the reference would divide by zero.
    return dist === 0 ? 1 : 0;
  }
  return 1 - dist / denom;
}
