/**
 * TEDS — Tree-Edit-Distance-based Similarity for table HTML.
 *
 * A faithful TypeScript port of the reference metric from IBM PubTabNet
 * (https://github.com/ibm-aur-nlp/PubTabNet, src/metric.py, commit
 * 8ffde9024bd331f5a61c3c549fdf30dd3c3e43a5), with zero runtime dependencies.
 *
 * Tree model (mirrors the reference `TableTree` built by `load_html_tree`):
 *   - element nodes under <table> in document order: table, thead, tbody,
 *     tfoot, tr, td (a <th> is normalized to td — all producers in this
 *     benchmark emit header cells as plain cells, and the reference is run
 *     with the same rewrite when generating fixtures);
 *   - td nodes carry {colspan, rowspan, content}; other nodes carry tag only.
 *
 * Cost model (reference `CustomConfig`):
 *   - insert = delete = 1;
 *   - rename(a, b) = 1 if tag, colspan, or rowspan differ; otherwise, for two
 *     td nodes with any content, levenshtein(contentA, contentB) / max(len);
 *     otherwise 0. In structureOnly mode cell content is treated as empty, so
 *     matching-span td pairs rename for free.
 *
 * Score (reference `TEDS.evaluate`):
 *   TEDS = 1 - editDistance / max(descendantCount(pred), descendantCount(gt))
 * where descendantCount counts every element node strictly below <table>
 * (the reference counts `table.xpath(".//*")`, which excludes the table root
 * even though the root participates in the edit distance). Empty or
 * unparseable input on either side scores 0.
 *
 * Documented normalizations (differences from raw lxml parsing, chosen so all
 * benchmark producers compare on equal footing; the committed fixtures were
 * generated by running the Python reference on identically-normalized input):
 *   - inline formatting tags inside cells (<b>, <i>, <sub>, <sup>, <span>,
 *     <br>, ...anything non-structural) are stripped, keeping their text —
 *     equivalent to running the reference with ignore_nodes=(those tags),
 *     which applies lxml's etree.strip_tags before building the tree;
 *   - <th> is treated as <td> (see above);
 *   - cell text has HTML entities decoded and whitespace runs collapsed to a
 *     single space, then is trimmed;
 *   - text outside cells (indentation between structural tags) is ignored,
 *     matching the reference, which never tokenizes non-td text.
 *
 * Algorithm: Zhang–Shasha tree edit distance (K. Zhang & D. Shasha, 1989)
 * rather than APTED. Both are *exact* optimal tree-edit-distance algorithms
 * for arbitrary per-node cost functions, so they return identical distances;
 * APTED only improves the worst-case constant/complexity. Zhang–Shasha runs
 * O(n1·n2·min(depth1,leaves1)·min(depth2,leaves2)) — table trees are ~3 deep,
 * so scoring a pair of ~2000-node trees takes well under a second. Cell-pair
 * string edit distances are memoized. Levenshtein operates on Unicode code
 * points to match Python's `list(text)` semantics.
 */

interface TableNode {
  tag: string;
  /** -1 for non-td nodes (mirrors Python None; -1 === -1 keeps rename at 0). */
  colspan: number;
  rowspan: number;
  /** Cell text for td nodes, null otherwise. */
  content: string | null;
  children: TableNode[];
}

/** Tags that become tree nodes; everything else inside <table> is inline. */
const STRUCTURAL = new Set(['table', 'thead', 'tbody', 'tfoot', 'tr', 'td']);

const NAMED_ENTITIES: Record<string, string> = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
};

function decodeEntities(text: string): string {
  return text.replace(/&(#x?[0-9a-fA-F]+|[a-zA-Z][a-zA-Z0-9]*);/g, (whole, body: string) => {
    if (body[0] === '#') {
      const hex = body[1] === 'x' || body[1] === 'X';
      const code = parseInt(body.slice(hex ? 2 : 1), hex ? 16 : 10);
      return Number.isFinite(code) && code >= 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
    }
    const named = NAMED_ENTITIES[body.toLowerCase()];
    return named !== undefined ? named : whole;
  });
}

function normalizeCellText(raw: string): string {
  return decodeEntities(raw).replace(/\s+/g, ' ').trim();
}

/** A parsed markup token: an open/close/self-closing tag. */
interface TagToken {
  name: string;
  closing: boolean;
  attrs: string;
  /** index just past the token in the source */
  end: number;
}

/** Parse the tag starting at `<` position `at`; null if malformed. */
function parseTag(src: string, at: number): TagToken | null {
  const m = /^<(\/?)([a-zA-Z][a-zA-Z0-9]*)((?:"[^"]*"|'[^']*'|[^>"'])*)\/?>/.exec(src.slice(at));
  if (!m) return null;
  return { name: m[2].toLowerCase(), closing: m[1] === '/', attrs: m[3], end: at + m[0].length };
}

function parseSpan(attrs: string, name: string): number {
  const m = new RegExp(`${name}\\s*=\\s*(?:"([^"]*)"|'([^']*)'|([^\\s"'>]+))`, 'i').exec(attrs);
  if (!m) return 1;
  const v = parseInt((m[1] ?? m[2] ?? m[3]).trim(), 10);
  return Number.isFinite(v) && v > 0 ? v : 1;
}

/**
 * Parse the first <table> element from an HTML string into a TableNode tree.
 * Restricted-subset parser: structural tags become nodes, inline tags inside
 * cells are stripped keeping text, comments are dropped. Returns null when no
 * parseable table exists.
 */
export function parseTableHtml(htmlStr: string): TableNode | null {
  const start = htmlStr.search(/<table[\s>/]/i);
  if (start < 0) return null;

  const root: TableNode = { tag: 'table', colspan: -1, rowspan: -1, content: null, children: [] };
  const stack: TableNode[] = [root];
  let i = parseTag(htmlStr, start)!.end;
  /** open td cell, if any (text accumulates here; inline tags stripped) */
  let cell: TableNode | null = null;
  let cellText = '';

  const closeCell = (): void => {
    if (cell) {
      cell.content = normalizeCellText(cellText);
      cell = null;
      cellText = '';
    }
  };

  while (i < htmlStr.length) {
    const lt = htmlStr.indexOf('<', i);
    if (lt < 0) break;
    if (lt > i && cell) cellText += htmlStr.slice(i, lt);

    if (htmlStr.startsWith('<!--', lt)) {
      const end = htmlStr.indexOf('-->', lt + 4);
      if (end < 0) break;
      i = end + 3;
      continue;
    }

    const tag = parseTag(htmlStr, lt);
    if (!tag) {
      // stray '<' — treat as text
      if (cell) cellText += '<';
      i = lt + 1;
      continue;
    }
    i = tag.end;

    const name = tag.name === 'th' ? 'td' : tag.name;
    if (!STRUCTURAL.has(name)) continue; // inline tag: strip, keep text

    if (name === 'td' && !tag.closing) {
      closeCell(); // implied close of a dangling cell
      const td: TableNode = {
        tag: 'td',
        colspan: parseSpan(tag.attrs, 'colspan'),
        rowspan: parseSpan(tag.attrs, 'rowspan'),
        content: '',
        children: [],
      };
      stack[stack.length - 1].children.push(td);
      cell = td;
      cellText = '';
      continue;
    }

    // any structural open/close tag implies the end of an open cell
    closeCell();

    if (tag.closing) {
      if (name === 'td') continue; // already closed above
      let depth = -1;
      for (let s = stack.length - 1; s >= 1; s--) {
        if (stack[s].tag === name) {
          depth = s;
          break;
        }
      }
      if (depth > 0) stack.length = depth; // pop to (and including) innermost match
      if (name === 'table') break; // done with the first table
      continue;
    }

    if (name === 'table') break; // nested table start: not supported, stop
    const node: TableNode = { tag: name, colspan: -1, rowspan: -1, content: null, children: [] };
    stack[stack.length - 1].children.push(node);
    stack.push(node);
  }
  closeCell();
  return root;
}

